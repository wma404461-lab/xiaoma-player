const {contextBridge,ipcRenderer,webUtils}=require('electron');
contextBridge.exposeInMainWorld('viewer',{
  pathsForFiles:files=>Array.from(files,file=>webUtils.getPathForFile(file)).filter(Boolean),
  scan:paths=>ipcRenderer.invoke('scan',paths),
  choose:mode=>ipcRenderer.invoke('choose',mode),
  refreshSequence:id=>ipcRenderer.invoke('refresh-sequence',id),
  reveal:id=>ipcRenderer.invoke('reveal',id),
  memoryBudget:()=>ipcRenderer.invoke('memory-budget'),
  initialPaths:()=>ipcRenderer.invoke('initial-paths'),
  fullscreen:()=>ipcRenderer.invoke('fullscreen'),
  appVersion:()=>ipcRenderer.invoke('app-version'),
  checkUpdate:()=>ipcRenderer.invoke('update-check'),
  downloadUpdate:()=>ipcRenderer.invoke('update-download'),
  installUpdate:()=>ipcRenderer.invoke('update-install'),
  onUpdateProgress:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('update-progress',listener);return ()=>ipcRenderer.removeListener('update-progress',listener);},
  onFullscreen:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('fullscreen-state',listener);return ()=>ipcRenderer.removeListener('fullscreen-state',listener);},
  documentPreview:id=>ipcRenderer.invoke('document-preview',id),
  subtitles:id=>ipcRenderer.invoke('subtitles',id),
  mediaInfo:id=>ipcRenderer.invoke('media-info',id),
  startExport:(id,options)=>ipcRenderer.invoke('export-start',id,options),
  exportFrame:(id,index,png)=>ipcRenderer.invoke('export-frame',id,index,png),
  finishExport:id=>ipcRenderer.invoke('export-finish',id),
  nextExportPass:id=>ipcRenderer.invoke('export-next-pass',id),
  cancelExport:id=>ipcRenderer.invoke('export-cancel',id),
  onExportProgress:callback=>{const listener=(_event,value)=>callback(value);ipcRenderer.on('export-progress',listener);return ()=>ipcRenderer.removeListener('export-progress',listener);},
  playerMenu:options=>ipcRenderer.invoke('player-menu',options),
  onPlayerAction:callback=>{const listener=(_event,action)=>callback(action);ipcRenderer.on('player-action',listener);return ()=>ipcRenderer.removeListener('player-action',listener);},
  onMediaChanged:callback=>{const listener=(_event,folder)=>callback(folder);ipcRenderer.on('media-changed',listener);return ()=>ipcRenderer.removeListener('media-changed',listener);},
  onOpenPaths:callback=>{const listener=(_event,paths)=>callback(paths);ipcRenderer.on('open-paths',listener);return ()=>ipcRenderer.removeListener('open-paths',listener);}
});
